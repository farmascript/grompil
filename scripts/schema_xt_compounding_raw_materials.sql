-- Shared catalogue foundation for raw materials used in pharmacy compounding.
-- This defines structure only; it does not import records from SAM, FAGG or RIZIV.
-- Keep substance identity, source identifiers and reimbursement rules separate:
-- each comes from a different authority and can have its own validity period.

BEGIN;

CREATE TABLE IF NOT EXISTS public.xt_compounding_raw_materials (
    id                          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    preferred_name_nl           TEXT NOT NULL DEFAULT '',
    preferred_name_fr           TEXT NOT NULL DEFAULT '',
    preferred_name_en           TEXT NOT NULL DEFAULT '',
    preferred_name_de           TEXT NOT NULL DEFAULT '',
    synonyms_nl                 TEXT[] NOT NULL DEFAULT ARRAY[]::TEXT[],
    synonyms_fr                 TEXT[] NOT NULL DEFAULT ARRAY[]::TEXT[],
    cas_number                  VARCHAR(32),
    ec_number                   VARCHAR(32),
    chemical_formula            TEXT,
    molecular_mass              NUMERIC(16, 7),
    pharmacopoeia_reference     TEXT,
    is_active                   BOOLEAN NOT NULL DEFAULT TRUE,
    source_payload_json         JSONB NOT NULL DEFAULT '{}'::JSONB,
    created_at                  TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at                  TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT xt_compounding_raw_materials_cas_number_nonempty_ck
        CHECK (cas_number IS NULL OR btrim(cas_number) <> ''),
    CONSTRAINT xt_compounding_raw_materials_ec_number_nonempty_ck
        CHECK (ec_number IS NULL OR btrim(ec_number) <> ''),
    CONSTRAINT xt_compounding_raw_materials_molecular_mass_positive_ck
        CHECK (molecular_mass IS NULL OR molecular_mass > 0),
    CONSTRAINT xt_compounding_raw_materials_payload_object_ck
        CHECK (JSONB_TYPEOF(source_payload_json) = 'object')
);

CREATE UNIQUE INDEX IF NOT EXISTS xt_compounding_raw_materials_cas_number_uidx
    ON public.xt_compounding_raw_materials (cas_number)
    WHERE cas_number IS NOT NULL;

CREATE INDEX IF NOT EXISTS xt_compounding_raw_materials_name_nl_idx
    ON public.xt_compounding_raw_materials (lower(preferred_name_nl));

CREATE INDEX IF NOT EXISTS xt_compounding_raw_materials_name_fr_idx
    ON public.xt_compounding_raw_materials (lower(preferred_name_fr));

CREATE TABLE IF NOT EXISTS public.xt_compounding_raw_material_sources (
    id                          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    raw_material_id             BIGINT NOT NULL
        REFERENCES public.xt_compounding_raw_materials(id) ON DELETE RESTRICT,
    source_system               VARCHAR(20) NOT NULL
        CHECK (source_system IN ('SAM', 'FAGG', 'RIZIV', 'OTHER')),
    source_record_type          VARCHAR(60) NOT NULL,
    external_id                 TEXT NOT NULL,
    source_version              VARCHAR(80) NOT NULL DEFAULT '',
    source_file                 TEXT NOT NULL DEFAULT '',
    source_status               TEXT NOT NULL DEFAULT '',
    valid_from                  DATE,
    valid_to                    DATE,
    source_payload_json         JSONB NOT NULL DEFAULT '{}'::JSONB,
    imported_at                 TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT xt_compounding_raw_material_sources_external_key_uq
        UNIQUE (source_system, source_record_type, external_id, source_version),
    CONSTRAINT xt_compounding_raw_material_sources_validity_ck
        CHECK (valid_to IS NULL OR valid_from IS NULL OR valid_to >= valid_from),
    CONSTRAINT xt_compounding_raw_material_sources_payload_object_ck
        CHECK (JSONB_TYPEOF(source_payload_json) = 'object')
);

CREATE INDEX IF NOT EXISTS xt_compounding_raw_material_sources_material_idx
    ON public.xt_compounding_raw_material_sources (raw_material_id);

CREATE INDEX IF NOT EXISTS xt_compounding_raw_material_sources_source_status_idx
    ON public.xt_compounding_raw_material_sources
       (source_system, source_record_type, source_status, valid_from, valid_to);

CREATE TABLE IF NOT EXISTS public.xt_compounding_reimbursement_codes (
    id                          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    raw_material_id             BIGINT NOT NULL
        REFERENCES public.xt_compounding_raw_materials(id) ON DELETE RESTRICT,
    chapter_code                VARCHAR(8) NOT NULL,
    reimbursement_code          VARCHAR(32) NOT NULL,
    list_number                 VARCHAR(40) NOT NULL DEFAULT '',
    description_nl              TEXT NOT NULL DEFAULT '',
    description_fr              TEXT NOT NULL DEFAULT '',
    conditions_nl               TEXT NOT NULL DEFAULT '',
    conditions_fr               TEXT NOT NULL DEFAULT '',
    valid_from                  DATE NOT NULL,
    valid_to                    DATE,
    source_version              VARCHAR(80) NOT NULL DEFAULT '',
    source_file                 TEXT NOT NULL DEFAULT '',
    source_payload_json         JSONB NOT NULL DEFAULT '{}'::JSONB,
    imported_at                 TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT xt_compounding_reimbursement_codes_chapter_ck
        CHECK (chapter_code IN ('I', 'II', 'III', 'IV', 'V', 'VI')),
    CONSTRAINT xt_compounding_reimbursement_codes_validity_ck
        CHECK (valid_to IS NULL OR valid_to >= valid_from),
    CONSTRAINT xt_compounding_reimbursement_codes_source_key_uq
        UNIQUE (raw_material_id, chapter_code, reimbursement_code, list_number, valid_from),
    CONSTRAINT xt_compounding_reimbursement_codes_payload_object_ck
        CHECK (JSONB_TYPEOF(source_payload_json) = 'object')
);

CREATE INDEX IF NOT EXISTS xt_compounding_reimbursement_codes_current_idx
    ON public.xt_compounding_reimbursement_codes
       (raw_material_id, chapter_code, valid_from, valid_to);

COMMENT ON TABLE public.xt_compounding_raw_materials IS
    'Shared canonical catalogue of substances/raw materials used for pharmacy compounding; not company stock or batch records.';
COMMENT ON TABLE public.xt_compounding_raw_material_sources IS
    'Source-specific identifiers, status, validity and preserved source data for SAM, FAGG and other raw-material records.';
COMMENT ON TABLE public.xt_compounding_reimbursement_codes IS
    'Dated RIZIV reimbursement/list-code associations and conditions for compounding raw materials.';
COMMENT ON COLUMN public.xt_compounding_raw_materials.source_payload_json IS
    'Optional preserved source fields that are not yet represented as dedicated columns.';
COMMENT ON COLUMN public.xt_compounding_raw_material_sources.external_id IS
    'Identifier exactly as published by that source; do not substitute the local surrogate id.';
COMMENT ON COLUMN public.xt_compounding_reimbursement_codes.chapter_code IS
    'RIZIV magistral-product chapter, retained as text because its legal meaning is source-defined.';
COMMENT ON COLUMN public.xt_compounding_reimbursement_codes.source_payload_json IS
    'Original RIZIV record fields, retained to avoid losing conditions or codes not yet mapped.';

COMMIT;
