-- Run this against the target database before importing data with explicit IDs.
-- The connected role must own the identity columns.

BEGIN;

DO $$
DECLARE
    identity_column RECORD;
BEGIN
    IF current_database() <> 'grompilc_test' THEN
        RAISE EXCEPTION 'This script is intended only for database grompilc_test; current database is %.',
            current_database();
    END IF;

    FOR identity_column IN
        SELECT table_schema, table_name, column_name
        FROM information_schema.columns
        WHERE table_schema = 'public'
          AND is_identity = 'YES'
    LOOP
        EXECUTE format(
            'ALTER TABLE %I.%I ALTER COLUMN %I SET GENERATED BY DEFAULT',
            identity_column.table_schema,
            identity_column.table_name,
            identity_column.column_name
        );
    END LOOP;
END;
$$;

COMMIT;
